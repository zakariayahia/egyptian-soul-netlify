// ===== MULTIPLE FILE UPLOAD =====
const uploadArea = document.getElementById('uploadArea');
const photoFile = document.getElementById('photoFile');
const previewContainer = document.getElementById('previewContainer');
let selectedFiles = [];
const MAX_FILES = 1;
const MAX_SIZE = 10 * 1024 * 1024; // 10MB

if (uploadArea && photoFile) {
  ['dragenter', 'dragover'].forEach(evt => {
    uploadArea.addEventListener(evt, (e) => {
      e.preventDefault();
      uploadArea.classList.add('dragover');
    });
  });

  ['dragleave', 'drop'].forEach(evt => {
    uploadArea.addEventListener(evt, (e) => {
      e.preventDefault();
      uploadArea.classList.remove('dragover');
    });
  });

  uploadArea.addEventListener('drop', (e) => {
    const files = Array.from(e.dataTransfer.files).filter(f => f.type.startsWith('image/'));
    addFiles(files);
  });

  photoFile.addEventListener('change', (e) => {
    addFiles(Array.from(e.target.files));
  });
}

function addFiles(files) {
  for (const file of files) {
    if (selectedFiles.length >= MAX_FILES) {
      showToast(currentLanguage === "en" ? "Maximum 1 photo only" : "الحد الأقصى صورة واحدة فقط", 'error');
      break;
    }
    if (file.size > MAX_SIZE) {
      showToast(currentLanguage === "en" ? `${file.name} is larger than 10MB` : `${file.name} أكبر من 10MB`, 'error');
      continue;
    }
    if (!file.type.startsWith('image/')) continue;
    selectedFiles.push(file);
  }
  renderPreviews();
}

function renderPreviews() {
  previewContainer.innerHTML = '';
  selectedFiles.forEach((file, idx) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      const div = document.createElement('div');
      div.className = 'preview-item';
      div.innerHTML = `
        <img src="${e.target.result}" alt="preview">
        <button class="remove-btn" onclick="removeFile(${idx})" type="button">✕</button>
      `;
      previewContainer.appendChild(div);
    };
    reader.readAsDataURL(file);
  });
}

function removeFile(index) {
  selectedFiles.splice(index, 1);
  renderPreviews();
  if (selectedFiles.length === 0) photoFile.value = '';
}

// ===== UPLOAD TO CLOUDINARY =====
async function uploadToCloudinary(file) {
  const url = `https://api.cloudinary.com/v1_1/${CLOUDINARY_CLOUD_NAME}/image/upload`;
  const formData = new FormData();
  formData.append('file', file);
  formData.append('upload_preset', CLOUDINARY_UPLOAD_PRESET);
  formData.append('folder', 'rouh_masrya');

  const res = await fetch(url, { method: 'POST', body: formData });
  if (!res.ok) throw new Error(currentLanguage === "en" ? 'Failed to upload photo' : 'فشل رفع الصورة على Cloudinary');
  const data = await res.json();
  return {
    url: data.secure_url,
    publicId: data.public_id,
    fileName: file.name,
    fileSize: file.size
  };
}

// ===== FORM SUBMISSION (CLOUDINARY + FIRESTORE) =====
const form = document.getElementById('registrationForm');
if (form) {
  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const submitBtn = document.getElementById('submitBtn');

    if (selectedFiles.length === 0) {
      showToast(currentLanguage === "en" ? 'Please upload one photo' : 'من فضلك ارفع صورة واحدة على الأقل', 'error');
      return;
    }

    // تأكد من تهيئة Firebase
    if (typeof db === 'undefined') {
      showToast(currentLanguage === "en" ? 'Database not initialized' : 'خطأ: لم يتم تهيئة قاعدة البيانات.', 'error');
      return;
    }

    submitBtn.disabled = true;
    submitBtn.innerHTML = `<div class="spinner" style="width:24px;height:24px;border-width:2px;"></div> ${translations[currentLanguage]['alert-submitting']}`;

    try {
      // 1. رفع كل الصور على Cloudinary
      const uploadedPhotos = [];
      for (const file of selectedFiles) {
        const photoData = await uploadToCloudinary(file);
        uploadedPhotos.push(photoData);
      }

      submitBtn.innerHTML = `<div class="spinner" style="width:24px;height:24px;border-width:2px;"></div> ${currentLanguage === "en" ? "Saving data..." : "جاري حفظ البيانات..."}`;

      // 2. تجهيز بيانات المشاركة
      const submission = {
        fullName: document.getElementById('fullName').value.trim(),
        email: document.getElementById('email').value.trim().toLowerCase(),
        phone: document.getElementById('phone').value.trim(),
        instagram: document.getElementById('instagram').value.trim(),
        theme: document.getElementById('theme').value,
        photoTitle: document.getElementById('photoTitle').value.trim(),
        photoDesc: document.getElementById('photoDesc').value.trim(),
        photos: uploadedPhotos,
        // للتوافق مع كود لوحة التحكم
        photoBase64: uploadedPhotos[0].url, 
        fileName: uploadedPhotos[0].fileName,
        fileSize: uploadedPhotos[0].fileSize,
        photoCount: uploadedPhotos.length,
        status: 'pending',
        rating: 0,
        submittedAt: new Date().toISOString()
      };

      // 3. حفظ البيانات في Firebase Firestore
      await db.collection("submissions").add(submission);

      showToast(translations[currentLanguage]['alert-success'], 'success');
      form.reset();
      selectedFiles = [];
      previewContainer.innerHTML = '';

    } catch (error) {
      console.error('Error:', error);
      showToast(translations[currentLanguage]['alert-error'], 'error');
    } finally {
      submitBtn.disabled = false;
      submitBtn.innerHTML = `<i class="fas fa-paper-plane"></i> <span>${translations[currentLanguage]['form-btn-submit']}</span>`;
    }
  });
}

// ===== MY SUBMISSIONS LOOKUP (FIRESTORE) =====
async function lookupSubmissions() {
  const email = document.getElementById('lookupEmail').value.trim().toLowerCase();
  const resultDiv = document.getElementById('mySubmissionsResult');

  if (!email) {
    showToast(currentLanguage === "en" ? 'Enter your email' : 'ادخل الإيميل الأول', 'error');
    return;
  }

  if (typeof db === 'undefined') {
    showToast('Database error', 'error');
    return;
  }

  resultDiv.innerHTML = '<div class="spinner" style="margin:20px auto;"></div>';

  try {
    const snapshot = await db.collection("submissions").where("email", "==", email).get();

    if (snapshot.empty) {
      resultDiv.innerHTML = `
        <div class="glass-card" style="text-align:center; padding:40px;">
          <i class="fas fa-inbox" style="font-size:2.5rem; color:var(--text-muted); margin-bottom:15px; display:block;"></i>
          <h3 style="color:var(--text-secondary); margin-bottom:8px;">${currentLanguage === 'en' ? 'No Entries' : 'لا توجد مشاركات'}</h3>
          <p style="color:var(--text-muted);">${translations[currentLanguage]['alert-no-submissions']}</p>
        </div>
      `;
      return;
    }

    const subs = [];
    snapshot.forEach(doc => {
      subs.push({ id: doc.id, ...doc.data() });
    });

    // Group by theme
    const byTheme = {};
    subs.forEach(s => {
      if (!byTheme[s.theme]) byTheme[s.theme] = [];
      byTheme[s.theme].push(s);
    });

    let html = `
      <div class="glass-card" style="padding:25px; margin-bottom:20px;">
        <div style="display:flex; align-items:center; gap:15px; flex-wrap:wrap;">
          <div style="flex:1;">
            <h3 style="color:var(--gold-primary); margin-bottom:5px;">
              <i class="fas fa-user"></i> ${subs[0].fullName}
            </h3>
            <p style="color:var(--text-secondary); font-size:0.9rem;">${subs[0].email}</p>
          </div>
          <div style="display:flex; gap:20px; text-align:center;">
            <div>
              <span style="font-size:1.8rem; font-weight:800; color:var(--gold-primary); display:block;">${subs.length}</span>
              <span style="color:var(--text-muted); font-size:0.8rem;">${currentLanguage === 'en' ? 'Entries' : 'مشاركة'}</span>
            </div>
            <div>
              <span style="font-size:1.8rem; font-weight:800; color:var(--gold-primary); display:block;">${Object.keys(byTheme).length}</span>
              <span style="color:var(--text-muted); font-size:0.8rem;">${currentLanguage === 'en' ? 'Themes' : 'محور'}</span>
            </div>
            <div>
              <span style="font-size:1.8rem; font-weight:800; color:var(--gold-primary); display:block;">${subs.reduce((sum, s) => sum + (s.photoCount || 1), 0)}</span>
              <span style="color:var(--text-muted); font-size:0.8rem;">${currentLanguage === 'en' ? 'Photos' : 'صورة'}</span>
            </div>
          </div>
        </div>
      </div>
    `;

    for (const [theme, themeSubs] of Object.entries(byTheme)) {
      // ترجمة اسم المحور المعروض في رأس المجموعة
      let themeDisplay = theme;
      if (currentLanguage === "en") {
        const mapping = { "تراث": "Heritage & Monuments", "شوارع": "Street Life", "طبيعة": "Nature & Landscapes", "بورتريه": "Portraits" };
        themeDisplay = mapping[theme] || theme;
      }
      
      html += `
        <h3 style="color:var(--text-primary); margin-bottom:15px; font-size:1.1rem;">
          <span style="background:rgba(212,160,23,0.15); padding:4px 12px; border-radius:20px; color:var(--gold-primary); font-size:0.85rem; border:1px solid rgba(212,160,23,0.3);">
            ${themeDisplay}
          </span>
          <span style="color:var(--text-muted); font-size:0.85rem; margin-${currentLanguage === 'en' ? 'left' : 'right'}:8px;">(${themeSubs.length} ${currentLanguage === 'en' ? 'Entry' : 'مشاركة'})</span>
        </h3>
      `;

      themeSubs.forEach(s => {
        const dateOptions = currentLanguage === 'en' ? { year: 'numeric', month: 'short', day: 'numeric' } : { year: 'numeric', month: 'short', day: 'numeric' };
        const date = new Date(s.submittedAt).toLocaleDateString(currentLanguage === 'en' ? 'en-US' : 'ar-EG', dateOptions);

        const statusColor = s.status === 'approved' ? 'color:#27AE60' :
                             s.status === 'rejected' ? 'color:#C0392B' : 'color:#F39C12';
        
        const statusText = s.status === 'approved' ? translations[currentLanguage]['sub-status-approved'] :
                           s.status === 'rejected' ? translations[currentLanguage]['sub-status-rejected'] : translations[currentLanguage]['sub-status-pending'];

        const photosHtml = (s.photos || [{ url: s.photoBase64 }]).map(p =>
          `<img src="${p.url || p.base64}" style="width:80px; height:80px; object-fit:cover; border-radius:8px; border:1px solid var(--dark-border);">`
        ).join('');

        // يظهر زر الحذف فقط للمشاركات التي ما زالت "في الانتظار" (pending) لحماية نزاهة المسابقة
        const deleteButton = s.status === 'pending' ? `
          <button class="btn btn-outline" onclick="cancelSubmission('${s.id}')" style="margin-top:10px; padding:6px 12px; font-size:0.8rem; border-color:#C0392B; color:#C0392B; display:inline-flex; align-items:center; gap:5px; background:transparent;">
            <i class="fas fa-trash"></i> ${translations[currentLanguage]['sub-btn-cancel']}
          </button>
        ` : '';

        html += `
          <div class="glass-card" style="padding:20px; margin-bottom:12px;">
            <div style="display:flex; gap:15px; align-items:flex-start; flex-wrap:wrap;">
              <div style="display:flex; gap:8px; flex-wrap:wrap;">${photosHtml}</div>
              <div style="flex:1; min-width:200px;">
                <h4 style="margin-bottom:5px;">${s.photoTitle}</h4>
                ${s.photoDesc ? `<p style="color:var(--text-secondary); font-size:0.85rem; margin-bottom:8px;">${s.photoDesc}</p>` : ''}
                <div style="display:flex; gap:15px; flex-wrap:wrap; font-size:0.8rem; color:var(--text-muted); align-items:center;">
                  <span><i class="fas fa-calendar"></i> ${date}</span>
                  <span><i class="fas fa-images"></i> ${s.photoCount || 1} ${currentLanguage === 'en' ? 'Photo' : 'صورة'}</span>
                  <span style="${statusColor}; font-weight:600;">${statusText}</span>
                </div>
                ${deleteButton}
              </div>
            </div>
          </div>
        `;
      });
    }

    resultDiv.innerHTML = html;

  } catch (error) {
    console.error(error);
    showToast(currentLanguage === 'en' ? 'Failed to lookup submissions' : 'فشل جلب المشاركات', 'error');
  }
}

// ===== CANCEL/DELETE SUBMISSION (FIRESTORE) =====
async function cancelSubmission(id) {
  const confirmCancel = confirm(translations[currentLanguage]['alert-cancel-confirm']);
  if (!confirmCancel) return;

  if (typeof db === 'undefined') {
    showToast('Database error', 'error');
    return;
  }

  try {
    await db.collection("submissions").doc(id).delete();
    showToast(translations[currentLanguage]['alert-cancel-success'], "success");
    // تحديث قائمة البحث تلقائياً
    lookupSubmissions();
  } catch (error) {
    console.error("Delete error:", error);
    showToast(currentLanguage === 'en' ? "Failed to cancel entry, please try again" : "فشل إلغاء المشاركة، حاول مرة أخرى", "error");
  }
}

// ===== SPONSOR MODAL =====
function openSponsorModal(index) {
  const sponsor = sponsorsData[index];
  if (!sponsor) return;

  document.getElementById('modalSponsorLogo').src = sponsor.logo;
  document.getElementById('modalSponsorName').textContent = sponsor.name;
  document.getElementById('modalSponsorDesc').textContent = sponsor.desc;
  document.getElementById('modalSponsorLink').href = sponsor.link;
  document.getElementById('sponsorModal').classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeSponsorModal() {
  document.getElementById('sponsorModal').classList.remove('active');
  document.body.style.overflow = '';
}

document.getElementById('sponsorModal')?.addEventListener('click', (e) => {
  if (e.target === e.currentTarget) closeSponsorModal();
});

document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') closeSponsorModal();
});

// ===== TOAST =====
function showToast(message, type = 'info') {
  const toast = document.getElementById('toast');
  toast.textContent = message;
  toast.className = `toast ${type} show`;
  setTimeout(() => { toast.classList.remove('show'); }, 3500);
}

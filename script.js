let currentLanguage = localStorage.getItem("favLanguage") || "ar";

// Apply Language
function applyLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem("favLanguage", lang);

  const html = document.getElementById("htmlTag");
  const body = document.body;
  const langToggleBtn = document.getElementById("langToggleBtn");
  const langBtnText = document.getElementById("langBtnText");

  if (lang === "en") {
    html.setAttribute("lang", "en");
    html.setAttribute("dir", "ltr");
    body.classList.add("lang-en");
    langBtnText.textContent = "عربي";
  } else {
    html.setAttribute("lang", "ar");
    html.setAttribute("dir", "rtl");
    body.classList.remove("lang-en");
    langBtnText.textContent = "EN";
  }

  // Update DOM Elements
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // Update Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang][key]) {
      el.setAttribute("placeholder", translations[lang][key]);
    }
  });

  // Update custom input hint
  const uploadHint = document.getElementById("photoUploadHint");
  const uploadLimitHint = document.getElementById("photoLimitHint");
  if (uploadHint && uploadLimitHint) {
    if (lang === "en") {
      uploadHint.textContent = "JPG, PNG - Max size 10MB - One photo only";
      uploadLimitHint.textContent = "(One photo only)";
    } else {
      uploadHint.textContent = "JPG, PNG - أقصى حجم 10MB - صورة واحدة فقط";
      uploadLimitHint.textContent = "(صورة واحدة فقط)";
    }
  }

  // Reload counters localized
  updateCountersLang(lang);
}

// Localize Counter Display
function updateCountersLang(lang) {
  document.querySelectorAll('.hero-stat .number').forEach(counter => {
    const count = parseInt(counter.getAttribute('data-count'));
    counter.textContent = lang === "ar" ? count.toLocaleString('ar-EG') : count.toLocaleString('en-US');
  });
}

// Toggle Language Click
function toggleLanguage() {
  const newLang = currentLanguage === "ar" ? "en" : "ar";
  applyLanguage(newLang);
}

// Run language initialization on DOM load
document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(currentLanguage);
});

